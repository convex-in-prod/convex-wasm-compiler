import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { promises as fs } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { promisify } from "node:util";
import test from "node:test";
import { installHermesSource, verifyHermesSource } from "./convex-wasm-hermes-source.mjs";

const exec = promisify(execFile);

test("patch-history replays independently of source commit identity and rejects dirty source", async t => {
  const root = await fs.realpath(await fs.mkdtemp(join(tmpdir(), "hermes-source-")));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const repo = join(root, "recipe");
  await fs.mkdir(repo);
  const git = async (...args) => (await exec("git", ["-C", repo, ...args])).stdout.trim();
  await git("init", "--quiet");
  await git("config", "user.name", "Source test");
  await git("config", "user.email", "source-test@localhost");
  await git("config", "commit.gpgsign", "false");
  await fs.writeFile(join(repo, "runtime.c"), "original\n");
  await git("add", ".");
  await git("commit", "-qm", "Upstream");
  const upstreamRevision = await git("rev-parse", "HEAD");
  await fs.writeFile(join(repo, "runtime.c"), "patched\n");
  await git("commit", "-qam", "Patch runtime");
  const sourceRevision = await git("rev-parse", "HEAD");
  const tree = await git("rev-parse", "HEAD^{tree}");
  const patch = await git("format-patch", "-1", "--stdout");
  await git("checkout", "--orphan", "patch-history");
  await git("rm", "-f", "runtime.c");
  await fs.mkdir(join(repo, "patches"));
  await fs.writeFile(join(repo, "patches/0001-runtime.patch"), `${patch}\n`);
  await fs.writeFile(join(repo, "SERIES"), `# patch-file source-commit\n0001-runtime.patch ${sourceRevision}\n`);
  await fs.writeFile(join(repo, "UPSTREAM"), `${upstreamRevision}\n`);
  await fs.writeFile(join(repo, "RESULT_TREE"), `${tree}\n`);
  await git("add", ".");
  await git("commit", "-qm", "Snapshot");
  const pin = { repository: repo, historyRevision: await git("rev-parse", "HEAD"), upstreamRevision, tree };
  const destination = join(root, "source");
  const installed = await installHermesSource(destination, { pin });
  assert.equal(installed.tree, tree);
  assert.notEqual(installed.revision, sourceRevision);
  assert.deepEqual(await installHermesSource(destination, { pin }), installed);
  await fs.mkdir(join(destination, "nested"));
  await assert.rejects(verifyHermesSource(join(destination, "nested"), { pin }), /must be clean/);
  await fs.writeFile(join(destination, "runtime.c"), "unexpected\n");
  await assert.rejects(verifyHermesSource(destination, { pin }), /must be clean/);
  await fs.writeFile(join(destination, "runtime.c"), "patched\n");
  await fs.writeFile(join(destination, "injected.h"), "unexpected\n");
  await assert.rejects(verifyHermesSource(destination, { pin }), /must be clean/);
  await assert.rejects(installHermesSource(join(root, "wrong-tree"), { pin: { ...pin, tree: "0".repeat(40) } }), /differs/);
});
